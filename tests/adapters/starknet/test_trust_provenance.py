FIX = Path(__file__).resolve().parents[2] / "fixtures" / "starknet"

PKG = '[package]\nname = "{name}"\nversion = "0.1.0"\n\n[dependencies]\nstarknet = "2.13.1"\n{deps}\n[[target.starknet-contract]]\n'
LOCK_HEAD = "# Code generated by scarb DO NOT EDIT.\nversion = 1\n"


def _lock(*names: str, extra: str = "") -> str:
    return LOCK_HEAD + "".join(f'\n[[package]]\nname = "{n}"\nversion = "0.1.0"\n' for n in names) + extra


def _tree(**over: str) -> dict[str, str]:
    files = {"Scarb.toml": PKG.format(name="hello", deps=""), "Scarb.lock": _lock("hello"), "src/lib.cairo": "fn f() {}\n"}
    files.update(over)
    return files


# --------------------------------------------------------------------------- trust scan

def test_plain_package_is_trusted() -> None:
    assert scan_files(_tree(), "") == (False, [])
    assert package_name(_tree(), "") == "hello"


def test_workspace_with_cairo_plugin_member_is_untrusted() -> None:
    files = {
        "Scarb.toml": '[workspace]\nmembers = ["a", "macros"]\n',
        "Scarb.lock": _lock("a", "m"),
        "a/Scarb.toml": PKG.format(name="a", deps=""),
        "macros/Scarb.toml": '[package]\nname = "m"\nversion = "0.1.0"\n\n[cairo-plugin]\n',
    }
    untrusted, reasons = scan_files(files, "a")
    assert untrusted and "cairo_plugin_in_tree:macros/Scarb.toml" in reasons


def test_virtual_workspace_without_package_is_untrusted() -> None:
    files = {"Scarb.toml": '[workspace]\nmembers = ["a"]\n', "Scarb.lock": _lock("a"),
             "a/Scarb.toml": PKG.format(name="a", deps="")}
    assert "virtual_workspace_no_package_selected" in scan_files(files, "")[1]


def test_workspace_path_dep_resolves_against_root() -> None:
    root = '[workspace]\nmembers = ["pkgs/a", "pkgs/b"]\n\n[workspace.dependencies]\nb = { path = "pkgs/b" }\n'
    files = {"Scarb.toml": root, "Scarb.lock": _lock("a", "b"),
             "pkgs/a/Scarb.toml": PKG.format(name="a", deps="b.workspace = true"),
             "pkgs/b/Scarb.toml": PKG.format(name="b", deps="")}
    assert scan_files(files, "pkgs/a") == (False, [])
    # Joined against the member dir it would be pkgs/a/pkgs/b (missing): must resolve at the root.
    files["Scarb.toml"] = root.replace('path = "pkgs/b"', 'path = "../b"')
    assert "path_dep_outside_tree:b" in scan_files(files, "pkgs/a")[1]


def test_path_dep_leaving_tree_is_untrusted() -> None:
    files = _tree(**{"Scarb.toml": PKG.format(name="hello", deps='x = { path = "../x" }')})
    assert "path_dep_outside_tree:x" in scan_files(files, "")[1]


def test_git_dependency_is_untrusted() -> None:
    files = _tree(**{"Scarb.toml": PKG.format(name="hello", deps='x = { git = "https://github.com/a/b", tag = "v1" }')})
    assert "git_dependency:x" in scan_files(files, "")[1]


def test_registry_dep_not_allowlisted_is_untrusted() -> None:
    lock = _lock("hello", extra='\n[[package]]\nname = "alexandria_math"\nversion = "0.5.0"\n'
                                'source = "registry+https://scarbs.xyz/"\nchecksum = "sha256:00"\n')
    files = _tree(**{"Scarb.toml": PKG.format(name="hello", deps='alexandria_math = "0.5.0"'), "Scarb.lock": lock})
    assert "external_package_not_allowlisted:alexandria_math@0.5.0" in scan_files(files, "")[1]


def test_allowlisted_plugin_still_untrusted() -> None:
    lock = _lock("hello", extra='\n[[package]]\nname = "snforge_scarb_plugin"\nversion = "0.51.2"\n'
                                'source = "registry+https://scarbs.xyz/"\n'
                                'checksum = "sha256:7b94edb0a94b93915200275076c29ef8266f4b870ffda04360cf36bc3b5e67cc"\n')
    assert "cairo_plugin_in_lock:snforge_scarb_plugin@0.51.2" in scan_files(_tree(**{"Scarb.lock": lock}), "")[1]


def test_lock_missing_and_unknown_lock_package() -> None:
    files = _tree()
    del files["Scarb.lock"]
    assert "lock_missing" in scan_files(files, "")[1]
    assert "lock_package_not_in_tree:ghost" in scan_files(_tree(**{"Scarb.lock": _lock("hello", "ghost")}), "")[1]


def test_patch_prebuilt_and_toolchain_files() -> None:
    files = _tree(**{"Scarb.toml": PKG.format(name="hello", deps="") + '\n[patch."https://x"]\n',
                     "rust-toolchain.toml": "[toolchain]\n"})
    reasons = scan_files(files, "")[1]
    assert any(r.startswith("patch_section") for r in reasons) and "toolchain_override:rust-toolchain.toml" in reasons
    pre = _tree(**{"Scarb.toml": PKG.format(name="hello", deps="") + '\n[tool.scarb]\nallow-prebuilt-plugins = ["x"]\n'})
    assert any(r.startswith("prebuilt_plugins_allowed") for r in scan_files(pre, "")[1])


# --------------------------------------------------------------------------- lock and artifacts (supervisor reads)

def test_stale_lock_detected(tmp_path: Path) -> None:
    files = _tree()
    (tmp_path / "tree").mkdir()
    (tmp_path / "tree" / "Scarb.lock").write_text(files["Scarb.lock"])
    assert lock_changed(tmp_path / "tree", files, "") is None
    (tmp_path / "tree" / "Scarb.lock").write_text(files["Scarb.lock"] + '\n[[package]]\nname = "new"\n')
    assert lock_changed(tmp_path / "tree", files, "") == "lock_changed_by_resolution"
    os.remove(tmp_path / "tree" / "Scarb.lock")
    (tmp_path / "elsewhere").write_text(files["Scarb.lock"])
    os.symlink(tmp_path / "elsewhere", tmp_path / "tree" / "Scarb.lock")
    assert lock_changed(tmp_path / "tree", files, "") == "lock_not_regular_file"


def test_read_artifacts_hashes_in_supervisor_and_skips_symlinks(tmp_path: Path) -> None:
    udc = json.loads((FIX / "udc_class_0x1b2df6d8.json").read_text())
    udc["abi"] = json.loads(udc["abi"])       # Scarb artifacts hold the ABI as a JSON array
    prof = tmp_path / "out" / "release"
    prof.mkdir(parents=True)
    (prof / "p_UDC.contract_class.json").write_text(json.dumps(udc))
