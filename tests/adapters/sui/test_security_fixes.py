def test_git_dep_in_move_lock_refused():
    """A git dep in Move.lock must be refused even if Move.toml has it as local.

    Escape closed: a local dep in Move.toml can point outside c.files to a
    directory whose Move.toml has git deps.  Those transitive deps appear in
    Move.lock but NOT in the direct Move.toml scan.
    """
    files = {"Move.lock": GIT_IN_LOCK}
    result = _check_move_lock(files)
    assert result is not None
    assert "git" in result.lower() or "non-local" in result.lower() or "TransitiveGitDep" in result


