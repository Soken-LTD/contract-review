def test_move_lock_with_pkg_dir():
    """Move.lock in a subdirectory (pkg_dir) is found by the right path."""
    files = {"packages/core/Move.lock": CLEAN_LOCK}
    assert _check_move_lock(files, "packages/core") is None
    # Wrong pkg_dir → absent → fail closed
    result = _check_move_lock(files, ".")
