# ── sui/build.py (wave-4): always --network=none; unknown lock variant → build fails ──

def test_sui_build_always_uses_network_none(monkeypatch):
    """The Sui build container MUST always use --network=none regardless of Move.toml/Move.lock.

    Wave-4 fix: removed the conditional deps step (which ran with egress network).
    Now sandbox.run is only called with step="build" → sandbox profile enforces
    --network=none.  A crafted manifest or lock file cannot change the network mode.
    """
    import subprocess
    from pathlib import Path

    from soken_review.adapters.move import sandbox

    recorded_argvs: list[list[str]] = []

    def fake_run_subprocess(argv, *, capture_output, timeout, check):
        recorded_argvs.append(argv)
        # Simulate a failed build (no artifacts produced)
        import types
        r = types.SimpleNamespace(returncode=1, stdout=b"build failed offline", stderr=b"")
        return r

    monkeypatch.setattr(subprocess, "run", fake_run_subprocess)
    monkeypatch.setattr(sandbox, "image_for", lambda chain: "sui@sha256:" + "a" * 64)
    monkeypatch.setattr(sandbox, "locked_image", lambda chain: "sui@sha256:" + "a" * 64)

    import tempfile

    from soken_review.adapters.base import Candidate
    from soken_review.adapters.sui.build import build

    # Test 1: clean local lock
    manifest = "[package]\nname = \"pkg\"\n[dependencies]\nSui = { local = \"/opt/sui-framework/sui-framework\" }"
    lock = CLEAN_LOCK  # all local deps

    c = Candidate(provider="sui_registry", files={"Move.toml": manifest, "Move.lock": lock},
                  sha256="abc", language="move_sui", compiler=None, settings={"chain": "sui"},
                  std_json_input=None, entry_contract=None)
    with tempfile.TemporaryDirectory() as tmp:
        build(c, Path(tmp))

    # Test 2: git dep in lock
    c2 = Candidate(provider="sui_registry", files={"Move.toml": manifest, "Move.lock": GIT_IN_LOCK},
                   sha256="abc", language="move_sui", compiler=None, settings={"chain": "sui"},
                   std_json_input=None, entry_contract=None)
    with tempfile.TemporaryDirectory() as tmp2:
        build(c2, Path(tmp2))

    # ALL docker run calls must use --network=none
    for argv in recorded_argvs:
        assert "--network=none" in argv, f"Expected --network=none in {argv}"
    # No call should use any egress network name
    for argv in recorded_argvs:
        assert not any("egress" in a for a in argv), f"Unexpected egress network in {argv}"


def test_sui_unknown_lock_variant_fails_build_not_network(monkeypatch):
    """An unknown Move.lock source variant causes a build failure, never network access.

    The build runs offline; if MOVE_HOME lacks the dep, sui move build fails.
    The supervisor maps build_failed to insufficient_source.  No condition on
    the lock file content ever grants the container network access.
    """
    import subprocess
    import tempfile
    import types
    from pathlib import Path

    from soken_review.adapters.base import Candidate
    from soken_review.adapters.move import sandbox
    from soken_review.adapters.sui.build import build

    def fake_run_subprocess(argv, *, capture_output, timeout, check):
        # Simulate build failure (offline, deps not found)
        r = types.SimpleNamespace(returncode=1, stdout=b"", stderr=b"error[E02001]: unresolved dependency")
        return r

    monkeypatch.setattr(subprocess, "run", fake_run_subprocess)
    monkeypatch.setattr(sandbox, "image_for", lambda chain: "sui@sha256:" + "b" * 64)

    # Lock with on-chain source (unknown form for offline build)
    c = Candidate(provider="sui_registry",
                  files={"Move.toml": "[package]\nname = \"p\"",
                         "Move.lock": ON_CHAIN_IN_LOCK},
                  sha256="abc", language="move_sui", compiler=None,
                  settings={"chain": "sui"}, std_json_input=None, entry_contract=None)
    with tempfile.TemporaryDirectory() as tmp:
        result = build(c, Path(tmp))

    # Build must fail — but through the offline build failure path, not a network call
    assert result.status == "failed"
    assert result.reason in ("build_failed", "deps_unreachable", "sandbox_unavailable",
                              "insufficient_source")
