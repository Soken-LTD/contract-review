def test_transitive_escape_caught_by_move_lock():
    """The structural escape: Move.toml has only local deps but Move.lock reveals a git dep.

    Scenario: top-level Move.toml has local = "../../outside_cache/some_pkg".
    That path is not in c.files so its Move.toml is not scanned.  The Sui CLI
    follows the path during dep resolution, finds its git dep, and records it in
    Move.lock.  The old Move.toml scan misses this; the Move.lock check catches it.
    """
    # Simulate: Move.toml looks clean (only local), but Move.lock has a transitive git dep
    direct_manifest = """\
[package]
name = "victim"

[dependencies]
LocalDep = { local = "../../outside_cache/some_pkg" }
"""
    files = {
        "Move.toml": direct_manifest,
        "Move.lock": GIT_IN_LOCK,   # git dep visible in resolved lock
    }
    # Old check (Move.toml scan alone) would miss this
    # New check reads Move.lock and catches it
    result = _check_move_lock(files)
    assert result is not None, "git dep in Move.lock must be caught even if not in Move.toml"


