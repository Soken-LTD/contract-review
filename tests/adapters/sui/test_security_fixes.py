# ── Tests: gitfetch peel verification ────────────────────────────────────────
# The peel check for annotated tags is now performed inside the soken-fetch binary
# (which runs on the correct egress network). The tests patch _repo_fetch.materialize_repo
# to simulate the outcomes soken-fetch would produce.

def test_fetch_repo_peel_check_on_tag_mismatch(monkeypatch):
    """Annotated-tag peel failure inside soken-fetch must propagate as FetchError.

    soken-fetch returns E_UNPINNED_REF (exit 24) when the tag object does not peel
    to the fetched commit. fetch_repo must raise FetchError in that case.
    """
    import pathlib
    import tempfile

    from soken_review.adapters.move import gitfetch
    from soken_review.sandbox.repo_fetch import FetchResult

    def fake_materialize(url, job_dir, family, commit=None, ref=None, **_kw):
        # soken-fetch detected peel mismatch → E_UNPINNED_REF
        return FetchResult(24, "E_UNPINNED_REF", False, job_dir / "src")

    monkeypatch.setattr(gitfetch._repo_fetch, "materialize_repo", fake_materialize)

    with tempfile.TemporaryDirectory() as tmp, pytest.raises(gitfetch.FetchError, match="E_UNPINNED_REF"):
        gitfetch.fetch_repo("https://github.com/foo/bar", "v1.2.3", pathlib.Path(tmp))


def test_fetch_repo_peel_check_passes_when_matching(monkeypatch):
    """When soken-fetch succeeds and resolved_commit is set, the fetch succeeds."""
    import pathlib
    import tempfile

    from soken_review.adapters.move import gitfetch
    from soken_review.sandbox.repo_fetch import FetchResult

    COMMIT = "aabbccdd" * 5

    def fake_materialize(url, job_dir, family, commit=None, ref=None, **_kw):
        src = job_dir / "src"
        src.mkdir(parents=True, exist_ok=True)
        return FetchResult(0, "", False, src, {"resolved_commit": COMMIT})

    monkeypatch.setattr(gitfetch._repo_fetch, "materialize_repo", fake_materialize)

    with tempfile.TemporaryDirectory() as tmp:
        _files, resolved = gitfetch.fetch_repo("https://github.com/foo/bar", "v1.2.3", pathlib.Path(tmp))
        assert resolved == COMMIT


def test_fetch_repo_peel_check_skipped_for_sha_ref(monkeypatch):
    """For SHA refs, soken-fetch is called with --commit (not --ref) and resolved_commit is verified.

    The supervisor checks resolved_commit == requested_sha; no separate peel step is needed
    because we specified an exact commit rather than a tag.
    """
    import pathlib
    import tempfile

    from soken_review.adapters.move import gitfetch
    from soken_review.sandbox.repo_fetch import FetchResult

    COMMIT = "aabbccdd" * 5
    calls: list[dict] = []

    def fake_materialize(url, job_dir, family, commit=None, ref=None, **_kw):
        calls.append({"commit": commit, "ref": ref})
        src = job_dir / "src"
        src.mkdir(parents=True, exist_ok=True)
        return FetchResult(0, "", False, src, {"resolved_commit": COMMIT})

    monkeypatch.setattr(gitfetch._repo_fetch, "materialize_repo", fake_materialize)

    with tempfile.TemporaryDirectory() as tmp:
        _files, resolved = gitfetch.fetch_repo("https://github.com/foo/bar", COMMIT, pathlib.Path(tmp))
        assert resolved == COMMIT
        # SHA ref must be passed as commit=, not ref=, so soken-fetch uses --commit
        assert len(calls) == 1
        assert calls[0]["commit"] == COMMIT
        assert calls[0]["ref"] is None


