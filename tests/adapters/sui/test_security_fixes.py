def test_hidden_code_in_spec_is_not_lost():
    """Code hidden in a spec-like construct must NOT be silently stripped.

    Before fix (wave-2 regex approach): `spec module { fun hidden() { attack() } }` would
    be refused if _FORBIDDEN matched.  But edge cases (nested constructs, macro calls,
    string literals containing 'fun') could escape refusal and be stripped.

    After fix (no-op): the entire text is passed through as-is.  Analysis sees
    'hidden()' and 'attack()' in the full source.  No lead is silently lost.
    """
    from soken_review.adapters.aptos.specs import strip_specs

    evil = "spec module { fun hidden(): u64 { steal_coins() } }"
    result, _rep = strip_specs(evil, "evil.move")
    # Must return original — the analyzer can find 'steal_coins' in the full text
    assert result == evil
    assert "steal_coins" in result


