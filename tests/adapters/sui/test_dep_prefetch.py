# ── Analyze timeout kills container ──────────────────────────────────────────

def test_analyze_timeout_kills_container(monkeypatch, tmp_path):
    """When sandbox.run times out, the container is killed via docker rm -f.
    (Tests the fix in sandbox.run: named container + TimeoutExpired handler.)
    """
    from soken_review.adapters.move import sandbox

    killed_names: list[str] = []
    captured_names: list[str] = []

    # docker_argv is imported directly into sandbox.py; patch it there.
    def fake_docker_argv(**kwargs):
        name = kwargs.get("name", "")
        captured_names.append(name)
        return ["docker", "run", "--rm", f"--name={name}", kwargs.get("image", ""), "echo"]

    monkeypatch.setattr(sandbox, "docker_argv", fake_docker_argv)
    monkeypatch.setattr(sandbox, "image_for", lambda chain: "soken/sui-build@sha256:abc")

    def fake_subprocess_run(argv, *args, **kwargs):
        argv_list = list(argv) if not isinstance(argv, list) else argv
        if len(argv_list) >= 4 and argv_list[:3] == ["docker", "rm", "-f"]:
            killed_names.append(argv_list[3])
            return subprocess.CompletedProcess(argv_list, 0, b"", b"")
        # Simulate timeout on the docker run
        raise subprocess.TimeoutExpired(argv_list, kwargs.get("timeout", 0), b"", b"")

    monkeypatch.setattr(subprocess, "run", fake_subprocess_run)

    dirs = {
        "src": tmp_path / "src",
        "out": tmp_path / "out",
        "move": tmp_path / "move",
        "host": tmp_path / "host",
    }
    for d in dirs.values():
        d.mkdir(parents=True, exist_ok=True)

    result = sandbox.run("sui", "analyze", dirs, ["sui", "move", "build"], timeout=1)

    assert result.timed_out, "expected timed_out=True"
    assert len(killed_names) == 1, f"expected exactly one docker rm -f, got: {killed_names}"
    assert killed_names[0].startswith("soken-move-analyze-"), killed_names[0]
    assert captured_names and killed_names[0] == captured_names[0], (
        f"killed container {killed_names[0]!r} != started container {captured_names[0]!r}"
    )
