# ── Move.lock bytes never modified ────────────────────────────────────────────

def test_populate_move_home_does_not_modify_lock_bytes(tmp_path, monkeypatch):
    """Move.lock is never rewritten: bytes before and after populate call are identical.
    Even if the dep is a framework dep, the lock file itself is unchanged.
    """
    from soken_review.adapters.move import sandbox as _sbx

    original_lock = FRAMEWORK_GIT_LOCK
    files = {"Move.lock": original_lock, "Move.toml": SHA_MANIFEST}

    # Stub sandbox.run to simulate copy success; dirs["move"] pre-created
    mock_dirs = {
        "src": tmp_path / "src",
        "out": tmp_path / "out",
        "move": tmp_path / "move",
        "host": tmp_path / "host",
    }
    for d in mock_dirs.values():
        d.mkdir(parents=True, exist_ok=True)

    def fake_run(chain, step, dirs, command, *, timeout, **kwargs):
        # Simulate cp by creating the cache dir
        if command[0] == "cp":
            # Create the directory that cp would create
            dest_parent = command[-1]
            src_name = Path(command[2]).name
            host_dest = mock_dirs["move"] / Path(dest_parent.lstrip("/")).parent / src_name
            host_dest.mkdir(parents=True, exist_ok=True)
        from soken_review.adapters.move.sandbox import RunResult
        return RunResult(0, "", "")

    monkeypatch.setattr(_sbx, "run", fake_run)

    populate_move_home_deps(files, ".", "sui", mock_dirs)

    # Move.lock bytes unchanged
    assert files["Move.lock"] == original_lock


