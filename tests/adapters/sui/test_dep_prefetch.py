# ── URL sanitize and cache path ───────────────────────────────────────────────

def test_dep_cache_url_sanitize_replaces_path_separators():
    """url_to_file_name in Sui CLI 1.81.1 replaces [/ : . @] with _.
    Source: external-crates/move/crates/move-package-alt/src/git/cache.rs
    """
    result = dep_cache_url_sanitize("https://github.com/MystenLabs/sui.git")
    assert "/" not in result
    assert ":" not in result
    assert "." not in result
    # Specific expected value derived from the Rust regex r"/|:|\.|@" → _
    assert result == "https___github_com_MystenLabs_sui_git"


def test_git_dep_cache_path_matches_cli_format():
    """Full cache path follows $MOVE_HOME/git/{url_sanitized}_{rev}/{subdir}."""
    path = git_dep_cache_path(
        "/work/move",
        "https://github.com/MystenLabs/sui.git",
        _FRAMEWORK_COMMIT,
        "crates/sui-framework/packages/sui-framework",
    )
    expected = (
        f"/work/move/git/https___github_com_MystenLabs_sui_git_{_FRAMEWORK_COMMIT}"
        f"/crates/sui-framework/packages/sui-framework"
    )
    assert path == expected


