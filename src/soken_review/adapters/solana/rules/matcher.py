"""soken-solana-rules matcher (06 section 3.5).

Python-based rule matcher that operates over extracted source patterns.
Input: files dict (path -> content) + extract output (from extract.py)
Output: list of SARIF-like findings (rule_id, file, start, end, severity, category)

Rules are defined in soken_solana_rules.yaml (reference data only).
Finding text is generated by the model; we only emit rule_id, location, severity.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

_RULES_PATH = Path(__file__).parent / "soken_solana_rules.yaml"

# Severity (SARIF level) -> lead.v1 severity_norm mapping per analyzer_severity.yaml
_SEVERITY_MAP = {"error": "High", "warning": "Medium", "note": "Low", "none": "Info"}
_TOOL_NAME = "soken-solana-rules"
_TOOL_VERSION = "0.1.0"


def _load_rules() -> list[dict]:
    """Load rule definitions from YAML (reference data)."""
    with _RULES_PATH.open() as fh:
        data = yaml.safe_load(fh)
    return data.get("rules", [])


@dataclass
class Finding:
    rule_id: str
    category: str
    severity_raw: str  # SARIF level
    file: str
    start: int
    end: int
    extra: dict = field(default_factory=dict)


# ---------------------------------------------------------------------------
# Pattern detectors (operate on source text)
# ---------------------------------------------------------------------------

# Anchor patterns
_INIT_IF_NEEDED = re.compile(r'\binit_if_needed\b')
_REMAINING_ACCOUNTS = re.compile(r'remaining_accounts')
_UNCHECKED_ACCOUNT = re.compile(r'UncheckedAccount|AccountInfo\b')
_SYSVAR_FROM_INFO = re.compile(r'AccountInfo.*sysvar|sysvar.*AccountInfo', re.IGNORECASE)
_INVOKE_SIGNED_RE = re.compile(r'\binvoke_signed\s*\(')
_INVOKE_RE = re.compile(r'\binvoke\s*\(')
_DECLARE_PROGRAM_RE = re.compile(r'declare_program!\s*\(')
_PROGRAM_ACCOUNT_RE = re.compile(r'Program\s*<')
_INTERFACE_RE = re.compile(r'Interface\s*<')
_TOKEN_INTERFACE_RE = re.compile(r'Interface\s*<\s*\'\w+,\s*(?:TokenInterface|token_interface)')
_ANCHOR_CLOSE_RE = re.compile(r'\bclose\s*=')
_INIT_RE = re.compile(r'\binit\b(?!_if_needed)')
_CHECKED_ARITH = re.compile(r'\b(?:checked_add|checked_sub|checked_mul|saturating_add|saturating_sub|saturating_mul)\b')
_RAW_ARITH_RE = re.compile(r'(?<![a-z_])(?:amount|balance|lamports|tokens|supply)[^;{}\n]*[+\-\*](?!=)')
_ABSOLUTE_IX_INDEX = re.compile(r'load_instruction_at\s*\(\s*[0-9]')
_LOADABLE_PROGRAM = re.compile(r'get_stack_height|current_index')


def _line_of(content: str, pos: int) -> int:
    """Return 1-based line number for character position pos in content."""
    return content[:pos].count("\n") + 1


def _find_pattern_lines(content: str, pattern: re.Pattern) -> list[tuple[int, int]]:
    """Return list of (start_line, end_line) for each match."""
    results = []
    for m in pattern.finditer(content):
        start_line = _line_of(content, m.start())
        end_line = _line_of(content, m.end())
        results.append((start_line, end_line))
    return results


# ---------------------------------------------------------------------------
# Framework-level detectors
# ---------------------------------------------------------------------------

def _check_anchor_files(files: dict[str, str], overflow_checks: str) -> list[Finding]:
    """Emit findings for Anchor programs."""
    findings: list[Finding] = []

    for path, content in files.items():
        if not path.endswith(".rs"):
            continue
        if not isinstance(content, str):
            continue

        # SOL-ACC-01: UncheckedAccount without signer context (simplified)
        for m in _UNCHECKED_ACCOUNT.finditer(content):
            line = _line_of(content, m.start())
            # Only flag if in an accounts struct (look for #[derive(Accounts)] nearby)
            nearby = content[max(0, m.start() - 500):m.start() + 200]
            if "Accounts" in nearby and "is_signer" not in nearby and "Signer" not in nearby:
                findings.append(Finding(
                    rule_id="SOL-ACC-01",
                    category="solana.missing_signer",
                    severity_raw="error",
                    file=path,
                    start=line,
                    end=line,
                ))

        # SOL-ACC-07: remaining_accounts without guard
        for start, end in _find_pattern_lines(content, _REMAINING_ACCOUNTS):
            nearby = content[max(0, content.find("remaining_accounts")) - 200:
                             content.find("remaining_accounts") + 500]
            if "owner" not in nearby and "key" not in nearby:
                findings.append(Finding(
                    rule_id="SOL-ACC-07",
                    category="solana.remaining_accounts",
                    severity_raw="warning",
                    file=path,
                    start=start,
                    end=end,
                ))
            break  # one per file

        # SOL-INIT-01: init_if_needed
        for start, end in _find_pattern_lines(content, _INIT_IF_NEEDED):
            findings.append(Finding(
                rule_id="SOL-INIT-01",
                category="solana.reinitialization",
                severity_raw="error",
                file=path,
                start=start,
                end=end,
            ))

        # SOL-ARITH-01: unchecked arithmetic on amounts when overflow_checks=off
        if overflow_checks == "off":
            for m in _RAW_ARITH_RE.finditer(content):
                line_s = _line_of(content, m.start())
                line_e = _line_of(content, m.end())
                # Check that there's no checked_* nearby
                nearby = content[max(0, m.start() - 30):m.end() + 30]
                if not _CHECKED_ARITH.search(nearby):
                    findings.append(Finding(
                        rule_id="SOL-ARITH-01",
                        category="solana.arithmetic",
                        severity_raw="error",
                        file=path,
                        start=line_s,
                        end=line_e,
                    ))

        # SOL-INTRO-01: absolute instruction index
        for start, end in _find_pattern_lines(content, _ABSOLUTE_IX_INDEX):
            findings.append(Finding(
                rule_id="SOL-INTRO-01",
                category="solana.introspection",
                severity_raw="warning",
                file=path,
                start=start,
                end=end,
            ))

    return findings


def _check_native_files(files: dict[str, str], overflow_checks: str) -> list[Finding]:
    """Emit findings for native (non-Anchor) programs."""
    findings: list[Finding] = []

    for path, content in files.items():
        if not path.endswith(".rs"):
            continue
        if not isinstance(content, str):
            continue

        # SOL-CPI-01: invoke with unchecked program
        for m in _INVOKE_RE.finditer(content):
            line = _line_of(content, m.start())
            # Check if the program account is validated nearby
            nearby = content[max(0, m.start() - 200):m.start() + 200]
            if "program_id" not in nearby and "key()" not in nearby:
                findings.append(Finding(
                    rule_id="SOL-CPI-01",
                    category="solana.arbitrary_cpi",
                    severity_raw="error",
                    file=path,
                    start=line,
                    end=line,
                ))

        # SOL-INIT-02: account initialization without guard
        # Look for write to account data without a discriminator check
        if re.search(r'\.try_borrow_mut_data|account_data\.copy_from_slice', content):  # noqa: SIM102
            if not re.search(r'initialized|discriminator|is_initialized', content):
                line = 1
                m = re.search(r'\.try_borrow_mut_data|account_data\.copy_from_slice', content)
                if m:
                    line = _line_of(content, m.start())
                findings.append(Finding(
                    rule_id="SOL-INIT-02",
                    category="solana.reinitialization",
                    severity_raw="error",
                    file=path,
                    start=line,
                    end=line,
                ))

        # SOL-ARITH-01
        if overflow_checks == "off":
            for m in _RAW_ARITH_RE.finditer(content):
                line_s = _line_of(content, m.start())
                line_e = _line_of(content, m.end())
                nearby = content[max(0, m.start() - 30):m.end() + 30]
                if not _CHECKED_ARITH.search(nearby):
                    findings.append(Finding(
                        rule_id="SOL-ARITH-01",
                        category="solana.arithmetic",
                        severity_raw="error",
                        file=path,
                        start=line_s,
                        end=line_e,
                    ))

    return findings


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_rules(
    files: dict[str, str],
    framework: str,
    overflow_checks: str = "unknown",
) -> list[dict]:
    """Run soken-solana-rules on the source files.

    Args:
        files: dict of path -> content
        framework: "anchor", "pinocchio", or "native"
        overflow_checks: "on", "off", or "unknown"

    Returns list of raw finding dicts compatible with analyze.py format.
    """
    findings: list[Finding] = []

    if framework == "anchor":
        findings.extend(_check_anchor_files(files, overflow_checks))
        # Anchor is built on top of native, also run native checks
        findings.extend(_check_native_files(files, overflow_checks))
    else:
        # native or pinocchio
        findings.extend(_check_native_files(files, overflow_checks))

    # Convert to raw finding dicts (same format as analyze.py uses)
    tool_tag = f"{_TOOL_NAME}@{_TOOL_VERSION}"
    results = []
    for f in findings:
        results.append({
            "tool": tool_tag,
            "rule_id": f"{_TOOL_NAME}:{f.rule_id}",
            "severity_raw": f.severity_raw,
            "file": f.file,
            "start": max(1, f.start),
            "end": max(1, f.end),
            "category": f.category,
        })
    return results


def version() -> str:
    """Return the rule pack version string."""
    try:
        with _RULES_PATH.open() as fh:
            data = yaml.safe_load(fh)
        return data.get("version", "0.1.0")
    except Exception:  # noqa: BLE001
        return "0.1.0"
