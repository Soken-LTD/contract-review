"""Database side of the rule tier generator and the operator switches (learning-loop design 2.2).

`recompute` reads `rule_stats` and the protection sources, runs `tiers.compute_tiers` and writes
a NEW immutable policy file plus a markdown diff for review. It never sets the flag: a version is
applied only after its pull request is merged and a person runs `activate`. `rollback` sets the
flag so the baseline is shown on the next `review_leads` call. Both switches are logged in
`admin_audit`.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml
from psycopg.rows import dict_row

from . import tiers
from .config import TIERS_DIR, config, current_salt, tag, token, valid_version

_JUDGE_SEV = ["Informational", "Low", "Medium", "High", "Critical"]


async def rule_stats(conn: Any) -> list[dict[str, Any]]:
    async with conn.cursor(row_factory=dict_row) as cur:
        await cur.execute("select * from rule_stats order by tool, rule_id")
        return [dict(r) for r in await cur.fetchall()]


async def protected_from_outcomes(conn: Any) -> set[tuple[str, str]]:
    """Rules with a judge-confirmed issue at or above the configured severity, and rules whose
    public-code promotion printed at or above `promoted_min_printed` (design 2.2 rule 5)."""
    prot = config()["protected"]
    jmin = _JUDGE_SEV.index(prot["judge_min_severity"]) if prot["judge_min_severity"] in _JUDGE_SEV else 2
    pmin = _JUDGE_SEV.index(prot["promoted_min_printed"]) if prot["promoted_min_printed"] in _JUDGE_SEV else 3
    out: set[tuple[str, str]] = set()
    async with conn.cursor() as cur:
        await cur.execute("select unnest(lead_rules) from judge_verdicts where real and judge_severity = any(%s)",
                          (_JUDGE_SEV[jmin:],))
        for (ref,) in await cur.fetchall():
            tool, _, rule = str(ref).partition(":")
            if tool and rule:
                out.add((tool, rule))
        await cur.execute("""select distinct tool, rule_id from lead_outcomes
                             where outcome = 'promoted' and consent_class = 'public_code'
                               and printed_severity = any(%s)""", (_JUDGE_SEV[pmin:],))
        out.update((str(t), str(r)) for t, r in await cur.fetchall())
    return out


async def recompute(conn: Any, new_version: str, previous_version: str | None, *,
                    tiers_dir: Path = TIERS_DIR, diff_path: Path | None = None) -> dict[str, Any]:
    if not valid_version(new_version) or new_version == tiers.baseline_version():
        raise ValueError(f"invalid new version {new_version!r}")
    target = tiers_dir / f"{new_version}.yaml"
    if target.exists():
        raise FileExistsError(f"{target} exists: policy versions are immutable")
    previous = tiers.load_policy(previous_version) if previous_version else None
    if previous_version and previous is None:
        raise FileNotFoundError(f"previous version {previous_version!r} not found")
    stats = await rule_stats(conn)
    extra = await protected_from_outcomes(conn)
    snapshot = datetime.now(UTC).strftime("%Y-%m-%dT%H:%MZ")
    doc, changes = tiers.compute_tiers(stats, previous, new_version, extra, snapshot)
    header = ("# Generated by scripts/learning_tiers.py recompute. Immutable: a change is a new version.\n"
              "# Not active until the learning.rule_tiers flag names this version (activate).\n")
    target.write_text(header + yaml.safe_dump(doc, sort_keys=False, width=120), encoding="utf-8")
    diff = tiers.render_diff(doc, changes, stats)
    if diff_path is not None:
        diff_path.write_text(diff, encoding="utf-8")
    tiers.load_policy.cache_clear()
    return {"path": str(target), "changes": len(changes), "rules": len(doc["rules"]), "diff": diff}


async def set_flag(conn: Any, value: dict[str, Any], actor: str) -> None:
    key = config()["flag_key"]
    actor = token("release", actor, "operator")
    async with conn.transaction():
        await conn.execute(
            """insert into flags (key, value, updated_by) values (%s, %s::jsonb, %s)
               on conflict (key) do update set value = excluded.value, updated_by = excluded.updated_by,
                                               updated_at = now()""",
            (key, json.dumps(value), actor))
        await conn.execute("insert into admin_audit (actor, action, target) values (%s, %s, %s)",
                           (actor, "learning.rule_tiers " + json.dumps(value, sort_keys=True)[:120], f"flag:{key}"))


async def activate(conn: Any, version: str, actor: str) -> None:
    if tiers.load_policy(version) is None:
        raise FileNotFoundError(f"policy version {version!r} not found in {TIERS_DIR}")
    await set_flag(conn, {"version": version}, actor)


async def rollback(conn: Any, actor: str, version: str | None = None) -> None:
    """Back to `version` (a previous reviewed policy) or, with none, to the baseline."""
    if version:
        await activate(conn, version, actor)
    else:
        await set_flag(conn, {"rollback": True}, actor)


async def import_judge(conn: Any, rows: list[dict[str, Any]]) -> int:
    """Load judge verdict rows (JSON appendix of a judgement). The target name is tagged under the
    learning salt and never stored; free text is not accepted."""
    salt = current_salt()
    n = 0
    async with conn.transaction(), conn.cursor() as cur:
        for r in rows:
            sev = str(r["judge_severity"])
            if sev not in _JUDGE_SEV:
                raise ValueError(f"judge_severity {sev!r}")
            lead_rules = [token("rule_id", x) for x in (r.get("lead_rules") or []) if token("rule_id", x) != "other"]
            await cur.execute(
                """insert into judge_verdicts (round, release, salt_id, target_tag, chain_family, arm, issue_id, real,
                                               judge_severity, printed_severity, claimed_severity, matrix_severity,
                                               severity_rule, lead_rules, source)
                   values (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                   on conflict (round, salt_id, target_tag, arm, issue_id) do nothing""",
                (token("release", r["round"]), token("release", r.get("release") or "unknown"), salt.salt_id,
                 tag("target", str(r["target"]), salt), token("family", r.get("chain_family"), "unknown"),
                 r["arm"], token("release", r["issue_id"]), bool(r["real"]), sev,
                 r.get("printed_severity") if r.get("printed_severity") in _JUDGE_SEV else None,
                 r.get("claimed_severity") if r.get("claimed_severity") in _JUDGE_SEV else None,
                 r.get("matrix_severity") if r.get("matrix_severity") in _JUDGE_SEV else None,
                 None, lead_rules, token("source", r.get("source") or "unknown", "unknown")))
            n += cur.rowcount if isinstance(cur.rowcount, int) and cur.rowcount > 0 else 0
    return n
